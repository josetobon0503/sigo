// Clip file names and ffmpeg settings for npm run videos:compress. Pure and with type-only imports, so
// plain Node can run it from the scripts and Jest can test it.

export type ClipChapter = 'howTo' | 'mistakes';
export type ReadyClips = Map<string, Set<ClipChapter>>; // exercise id -> compressed clips

const SUFFIX: Record<string, ClipChapter> = { como: 'howTo', no: 'mistakes' };
const SUFFIX_OF: Record<ClipChapter, string> = { howTo: 'como', mistakes: 'no' };

export const MAX_CLIP_BYTES = 3 * 1024 * 1024;
// Development clip: a solid color, not an exercise. Never listed as ready.
export const TEST_CLIP = '_test.mp4';

export type ParsedClip =
  | { ok: true; id: string; chapter: ClipChapter; output: string }
  | { ok: false; reason: 'name' | 'unknownId' };

// "<id>__como.mov" -> howTo of <id>, compressed to "<id>__como.mp4".
export function parseClipName(file: string, ids: ReadonlySet<string>): ParsedClip {
  const match = /^(.+)__(como|no)\.(mov|mp4)$/i.exec(file);
  if (!match) return { ok: false, reason: 'name' };
  const [, id, suffix] = match;
  if (!ids.has(id)) return { ok: false, reason: 'unknownId' };
  const chapter = SUFFIX[suffix.toLowerCase()];
  return { ok: true, id, chapter, output: clipFile(id, chapter) };
}

export function clipFile(id: string, chapter: ClipChapter): string {
  return `${id}__${SUFFIX_OF[chapter]}.mp4`;
}

// H.264 720p, 30 fps, no audio, CRF 28, moov atom first so it starts playing while it loads.
export function ffmpegArgs(input: string, output: string): string[] {
  return [
    '-y',
    '-i',
    input,
    '-vf',
    'scale=-2:720,fps=30',
    '-c:v',
    'libx264',
    '-preset',
    'slow',
    '-crf',
    '28',
    '-pix_fmt',
    'yuv420p',
    '-an',
    '-movflags',
    '+faststart',
    output,
  ];
}

// The compressed files in assets/videos/ that belong to an exercise.
export function readyClips(files: readonly string[], ids: ReadonlySet<string>): ReadyClips {
  const ready: ReadyClips = new Map();
  for (const file of files) {
    const clip = parseClipName(file, ids);
    if (!clip.ok || clip.output !== file) continue; // only our own .mp4 output names
    if (!ready.has(clip.id)) ready.set(clip.id, new Set());
    ready.get(clip.id)!.add(clip.chapter);
  }
  return ready;
}

// Source of src/data/videos.ts. Metro needs a literal require for each bundled file.
export function renderVideosModule(ready: ReadyClips): string {
  const rows = [...ready.keys()].sort().map((id) => {
    const chapters = (['howTo', 'mistakes'] as const)
      .filter((c) => ready.get(id)!.has(c))
      .map((c) => `${c}: require('../../assets/videos/${clipFile(id, c)}')`);
    return `  '${id}': { ${chapters.join(', ')} },`;
  });
  return `// Generated by npm run videos:compress from assets/videos/. Do not edit by hand.
// Local clips are for development only: before publishing, point these at CDN URLs ({ uri }).
import type { VideoRef } from '../engine/types';

export const videos: Record<string, { howTo?: VideoRef; mistakes?: VideoRef }> = ${rows.length ? `{\n${rows.join('\n')}\n}` : '{}'};
`;
}
